export function news(status?: string) {
  const priority =
    status === "NEEDS_INFO"
      ? "prepare-documents"
      : status === "OFFERED"
        ? "accept-offer"
        : status === "REJECTED"
          ? "after-rejection"
          : "working-capital";
  return [
    ...new Set([priority, "trade-seasonality", ...articles.map((a) => a.id)]),
  ]
    .slice(0, 4)
    .map((id) => {
      const { body: _body, ...article } = articles.find((a) => a.id === id)!;
      return {
        ...article,
        relevanceReason:
          id === priority
            ? "Подобрано для вашего текущего этапа"
            : "Для компаний в сфере торговли",
        isDemoMaterial: true as const,
      };
    });
}
